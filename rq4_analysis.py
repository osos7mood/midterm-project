from google.colab import files
import pandas as pd

up=files.upload()
fn=next(iter(up))
df=pd.read_excel(fn)

text=df["LLM_output"].astype(str).str.replace("\\n","\n",regex=False)
anys=df[["prompt_id","LLM_name"]].copy()
anys["LLM_name"]=anys["LLM_name"].replace({"GPT":"ChatGPT"})

anys["word_count"]=text.str.split().str.len()

anys["has_bullets"]=text.str.contains(r"(?m)^\s*(?:[-*•]|\d+[.)])\s+\S",regex=True)
anys["has_headings"]=text.str.contains(r"(?m)^\s{0,3}#{1,6}\s+\S",regex=True)
anys["has_bold"]=text.str.contains(r"\*\*\S.*?\*\*",regex=True)

words=text.str.lower().str.findall(r"\b\w+\b")
anys["vocabulary_diversity"]=words.apply(lambda tokens:len(set(tokens))/len(tokens) if tokens else 0)

sum=anys.groupby("LLM_name")[
    ["word_count",
     "has_bullets",
     "has_headings",
     "has_bold",
     "vocabulary_diversity"]].mean()

sum[["has_bullets","has_headings","has_bold"]]*=100
sum.columns=[
    "Average words",
    "Responses with bullets (%)",
    "Responses with headings (%)",
    "Responses with bold (%)",
    "Average vocabulary diversity"]
summ=sum.reindex(["ChatGPT","Claude","Gemini"])
display(summ.round(3))